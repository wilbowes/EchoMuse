# Emits mel_table.h from the openWakeWord melspectrogram.onnx: the 32 mel
# filters as (first FFT bin, taps). The model's own table, so the native
# path is held to the model and not to a formula that may not match it.
import onnx, numpy as np, sys
from onnx import numpy_helper
m = onnx.load(sys.argv[1]); inits = {t.name: numpy_helper.to_array(t) for t in m.graph.initializer}
W = inits["1.melW"]; assert W.shape == (257, 32)
maxtaps = max(len(np.nonzero(W[:,j])[0]) for j in range(32))
out = ["/* generated by gen_mel_table.py from melspectrogram.onnx (openWakeWord, Apache-2.0); do not edit */",
       "#define EM_MEL_BINS 32", f"#define EM_MEL_MAXTAPS {maxtaps}",
       "static const int em_mel_start[EM_MEL_BINS] = {" + ", ".join(str(int(np.nonzero(W[:,j])[0][0])) for j in range(32)) + "};",
       "static const int em_mel_ntaps[EM_MEL_BINS] = {" + ", ".join(str(len(np.nonzero(W[:,j])[0])) for j in range(32)) + "};",
       "static const float em_mel_w[EM_MEL_BINS][EM_MEL_MAXTAPS] = {"]
for j in range(32):
    nz = np.nonzero(W[:,j])[0]; s, e = nz[0], nz[-1]
    assert e-s+1 == len(nz), "filter must be contiguous"
    vals = [f"{float(v):.9e}f" for v in W[s:e+1, j]] + ["0.0f"]*(maxtaps-len(nz))
    out.append("  {" + ", ".join(vals) + "},")
out.append("};")
clip_lo = float(inits["onnx::Clip_39"]); print("clip_lo", clip_lo, file=sys.stderr)
out.append(f"#define EM_MEL_CLIP_LO {clip_lo:.9e}f")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
