#!/bin/sh
# Re-vendors libopus: the decoder sources in sources.txt and the headers beside
# them, byte-identical to the release, plus one wrapper .c per source in this
# directory (cgo only compiles .c files here, and a wrapper keeps upstream's
# relative includes resolving). NEON files get an _arm suffix so host builds
# skip them. Run from this directory; it replaces libopus/ and the wrappers.
set -eu
VER=1.5.2
SHA=65c1d2f78b9f2fb20082c38cbe47c951ad5839345876e46941612ee87f9a7ce1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL -o "$tmp/opus.tar.gz" "https://downloads.xiph.org/releases/opus/opus-$VER.tar.gz" ||
	curl -fsSL -o "$tmp/opus.tar.gz" "https://github.com/xiph/opus/releases/download/v$VER/opus-$VER.tar.gz"
echo "$SHA  $tmp/opus.tar.gz" | sha256sum -c -
tar -xzf "$tmp/opus.tar.gz" -C "$tmp"
src="$tmp/opus-$VER"
rm -rf libopus zz_*.c
mkdir -p libopus
cp "$src/COPYING" "$src/AUTHORS" libopus/
for d in include celt celt/arm silk silk/arm src; do
	mkdir -p "libopus/$d"
	cp "$src/$d"/*.h "libopus/$d/" 2>/dev/null || true
done
while read -r f; do
	cp "$src/$f" "libopus/$f"
	name="zz_$(echo "${f%.c}" | tr '/' '_')"
	case "$f" in *neon*) name="${name}_arm" ;; esac
	printf '// Generated by vendor.sh; do not edit.\n#include "libopus/%s"\n' "$f" > "$name.c"
done < sources.txt
echo "libopus $VER vendored: $(wc -l < sources.txt) sources"
