"""
Where every config key goes: docs/config-keys.md, generated from the code.

The list of config keys used to be written by hand in CLAUDE.md and drifted:
it missed consoleTimeoutMin and listed nsAsr and owwSpeexNs as device keys,
though only the controller reads them. This builds the table from the sources
that decide each column, so it cannot drift without tests/test_config_map.py
failing:

    python controller/tools/config_map.py

- Section, fleet-only, state: em_config_sections
- Default: em_db.DEFAULT_DEVICE_CONFIG
- Type: em_config_types.KINDS
- Echo: a field of device/internal/config ConfigMessage, or read by em_scenes
  (which compiles it into listeningAnim)
- Controller: modules holding the key as a string literal in code, not prose,
  leaving out the modules that only define keys
- Dashboard: named in static/dashboard.jsx
"""

from __future__ import annotations

import ast
import json
import re
import sys
from pathlib import Path

CONTROLLER = Path(__file__).resolve().parents[1]
REPO = CONTROLLER.parent
OUT = REPO / "docs" / "config-keys.md"
CONFIG_GO = REPO / "device" / "internal" / "config" / "config.go"
DASHBOARD = CONTROLLER / "static" / "dashboard.jsx"

# Modules that declare keys rather than act on them.
DEFINITIONS = {"em_db", "em_config_sections", "em_config_types"}

sys.path.insert(0, str(CONTROLLER))

import em_config_sections as S  # noqa: E402
import em_config_types as T  # noqa: E402
import em_db  # noqa: E402


def go_fields() -> list[str]:
    """ConfigMessage's JSON keys, in declaration order."""
    src = CONFIG_GO.read_text()
    body = src.split("type ConfigMessage struct {", 1)[1].split("\n}", 1)[0]
    return re.findall(r'^\s*\w+\s+\S+\s+`json:"(\w+)', body, re.M)


def literals(path: Path) -> set[str]:
    """String constants in a module's code. Docstrings are expression
    statements, so they are skipped; comments never reach the AST."""
    tree = ast.parse(path.read_text())
    docstrings = {id(n.value) for n in ast.walk(tree)
                  if isinstance(n, ast.Expr) and isinstance(n.value, ast.Constant)}
    return {n.value for n in ast.walk(tree)
            if isinstance(n, ast.Constant) and isinstance(n.value, str)
            and id(n) not in docstrings}


def section_of(key: str) -> str:
    if key in S.STATE_KEYS:
        return "state"
    for section in S.SECTIONS.values():
        if key in section["keys"]:
            label = section["label"]
            return f"{label} (fleet only)" if key in S.FLEET_KEYS else label
    return "none"


def default_of(key: str) -> str:
    if key not in em_db.DEFAULT_DEVICE_CONFIG:
        return "—"
    return f"`{json.dumps(em_db.DEFAULT_DEVICE_CONFIG[key])}`"


def keys() -> list[str]:
    """Every key the controller stores or a section names, sorted."""
    named = {k for s in S.SECTIONS.values() for k in s["keys"]}
    return sorted(set(em_db.DEFAULT_DEVICE_CONFIG) | named | S.STATE_KEYS,
                  key=str.lower)


def render() -> str:
    on_device = set(go_fields())
    modules = {p.stem: literals(p)
               for p in sorted(CONTROLLER.glob("em_*.py"))
               if p.stem not in DEFINITIONS}
    scenes = modules.get("em_scenes", set())
    dashboard = DASHBOARD.read_text()

    rows = []
    for key in keys():
        if key in on_device:
            echo = "yes"
        elif key in scenes:
            echo = "via `listeningAnim`"
        else:
            echo = "no"
        readers = ", ".join(m for m, lits in modules.items() if key in lits)
        shown = "yes" if re.search(rf"\b{key}\b", dashboard) else "no"
        rows.append(f"| `{key}` | {section_of(key)} | {default_of(key)} | "
                    f"{T.KINDS.get(key, '—')} | {echo} | {readers or '—'} | {shown} |")

    stored = set(keys())
    extra = [k for k in go_fields() if k not in stored]
    return "\n".join([
        "# Config keys",
        "",
        "Generated by `controller/tools/config_map.py`; do not edit by hand.",
        "`controller/tests/test_config_map.py` fails when this is out of date.",
        "",
        "- **Section**: the dashboard stage a device can override. *fleet only*",
        "  keys are never overridden per device; *state* is written by the",
        "  controller from what the Echo reports.",
        "- **Type**: what the API accepts (`em_config_types`); — means the key is",
        "  validated where it is handled.",
        "- **Echo**: whether the Echo applies it. *no* keys are still sent and",
        "  ignored; the controller acts on them itself.",
        "- **Controller**: modules that read or write it, besides the ones that",
        "  only declare it.",
        "",
        "| Key | Section | Default | Type | Echo | Controller | Dashboard |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        "Also on the config message, but not stored as config: "
        + ", ".join(f"`{k}`" for k in extra) + ".",
        "",
    ])


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
